// Reads every image in public/products and public/images and writes their pixel sizes to
// src/data/image-manifest.ts, so pages can reserve the right space (no layout shift).
// Run after adding or replacing photos:  npm run images
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function size(buf, ext) {
  if (ext === ".webp") {
    const chunk = buf.toString("ascii", 12, 16);
    if (chunk === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
    if (chunk === "VP8L") {
      const b = buf.readUInt32LE(21);
      return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
    }
    if (chunk === "VP8X") return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1];
  }
  if (ext === ".png") return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  if (ext === ".jpg" || ext === ".jpeg") {
    let i = 2;
    while (i < buf.length) {
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
        return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
      i += 2 + len;
    }
  }
  throw new Error("Unsupported image: " + ext);
}

const entries = [];
for (const dir of ["products", "images"]) {
  for (const f of readdirSync(join(root, "public", dir)).sort()) {
    const ext = extname(f).toLowerCase();
    if (![".webp", ".jpg", ".jpeg", ".png"].includes(ext)) continue;
    const [w, h] = size(readFileSync(join(root, "public", dir, f)), ext);
    entries.push(`  ${JSON.stringify(basename(f, ext))}: { src: "/${dir}/${f}", width: ${w}, height: ${h} },`);
  }
}
writeFileSync(
  join(root, "src/data/image-manifest.ts"),
  `// AUTO-GENERATED by scripts/gen-image-manifest.mjs — do not edit by hand. Run \`npm run images\`.\nexport const imageManifest: Record<string, { src: string; width: number; height: number }> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Wrote ${entries.length} images to src/data/image-manifest.ts`);
